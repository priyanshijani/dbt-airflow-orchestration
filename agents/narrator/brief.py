"""Steps 3 and 4: verify the model's brief against the evidence, then render Markdown.

A driver is kept only if it cites real evidence and every figure it quotes can be found in that evidence.
Rejected drivers are listed in `verification`, so a hallucination is visible rather than silently shipped.
"""
import re

AMOUNT = re.compile(r"\$\s?(\d[\d,]*(?:\.\d+)?)\s?([kKmM])?")
PERCENT = re.compile(r"(\d+(?:\.\d+)?)\s?%")


def _close(value: float, pool: list[float], tol: float) -> bool:
    return any(abs(p - value) <= tol for p in pool)


def unsupported_figures(text: str, pool: list[float]) -> list[str]:
    """Dollar amounts and percentages in text that match nothing in the evidence."""
    bad = []
    for num, suffix in AMOUNT.findall(text):
        v = float(num.replace(",", "")) * {"": 1, "k": 1e3, "m": 1e6}[suffix.lower()]
        if not _close(v, pool, max(1.0, (0.03 if suffix else 0.005) * v)):
            bad.append(f"${num}{suffix}")
    ratios = [p * 100 for p in pool if p < 20]  # stored as fractions (0.052) but quoted as 5.2%
    for num in PERCENT.findall(text):
        v = float(num)
        if not (_close(v, pool, 0.6) or _close(v, ratios, 0.6)):
            bad.append(f"{num}%")
    return bad


def verify(brief: dict, evidence_ids: set[str], pool: list[float]) -> dict:
    notes, kept = [], []
    for d in brief.get("drivers", []):
        cited = [e for e in d.get("evidence", []) if e in evidence_ids]
        title = d.get("title", "(untitled)")
        if not cited:
            notes.append(f"Dropped '{title}': cites no valid evidence")
            continue
        impact = d.get("impact_usd")
        if impact not in (None, "") and not _close(abs(float(impact)), pool, 1.0):
            notes.append(f"Dropped '{title}': impact ${impact} is not in the evidence")
            continue
        bad = unsupported_figures(f"{title}. {d.get('explanation', '')}", pool)
        if bad:
            notes.append(f"Dropped '{title}': figures not in evidence: {', '.join(bad)}")
            continue
        kept.append({**d, "evidence": cited})
    bad_head = unsupported_figures(f"{brief.get('headline', '')} {brief.get('summary', '')}", pool)
    out = {**brief, "drivers": kept}
    if bad_head:
        notes.append(f"Headline or summary quotes figures not in evidence: {', '.join(bad_head)}")
    out["verification"] = {"passed": not notes, "notes": notes}
    return out


def render(brief: dict, week: str, meta: dict) -> str:
    arrow = {"up": "🟢 ▲", "down": "🔴 ▼", "flat": "⚪ ■"}
    lines = [f"# Weekly revenue brief · week of {week}", "", f"**{brief['headline']}**", "", brief.get("summary", ""), "",
             "## What moved revenue", ""]
    if not brief["drivers"]:
        lines.append("_No driver passed verification._")
    for d in brief["drivers"]:
        impact = f" ({'+' if d['impact_usd'] >= 0 else '-'}${abs(d['impact_usd']):,.0f})" if d.get("impact_usd") not in (None, "") else ""
        lines += [f"- {arrow.get(d.get('direction'), '⚪ ■')} **{d['title']}**{impact}  ",
                  f"  {d['explanation']}  ", f"  _Evidence: {', '.join(d['evidence'])}_"]
    lines += ["", "## Check next", ""] + [f"- {w}" for w in brief.get("watch_items", [])]
    lines += ["", "## Caveats", ""] + [f"- {c}" for c in brief.get("caveats", [])]
    v = brief["verification"]
    lines += ["", "---",
              f"Verification: {'all figures traced to the data' if v['passed'] else 'issues found'} · "
              f"generated by {meta['model']} ({meta['mode']} mode)"]
    lines += [f"- ⚠️ {n}" for n in v["notes"]]
    return "\n".join(lines) + "\n"
